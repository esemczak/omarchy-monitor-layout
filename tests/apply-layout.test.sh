#!/bin/bash
# Exercises the shell helpers against a temporary HOME with a fake hyprctl.
# Run: bash tests/apply-layout.test.sh

set -uo pipefail

repo=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

export HOME="$tmp/home"
export XDG_CONFIG_HOME="$HOME/.config"
export XDG_STATE_HOME="$HOME/.local/state"
mkdir -p "$HOME/.config/hypr" "$tmp/bin"

# Fake hyprctl: records calls, returns configurable errors.
cat > "$tmp/bin/hyprctl" <<'EOF'
#!/bin/bash
echo "$*" >> "$HYPRCTL_LOG"
case "$1" in
  reload) exit 0 ;;
  configerrors) cat "$HYPRCTL_ERRORS" 2>/dev/null; exit 0 ;;
  monitors) cat "$HYPRCTL_MONITORS" 2>/dev/null || echo "[]"; exit 0 ;;
esac
EOF
cat > "$tmp/bin/omarchy-hyprland-reload-guard" <<'EOF'
#!/bin/bash
[[ -f "$GUARD_PAUSED" ]]
EOF
chmod +x "$tmp/bin/"*
export PATH="$tmp/bin:$PATH"
export HYPRCTL_LOG="$tmp/hyprctl.log"
export HYPRCTL_ERRORS="$tmp/errors.txt"
export HYPRCTL_MONITORS="$tmp/monitors.json"
export GUARD_PAUSED="$tmp/paused"

failures=0
not_grep() { ! grep "$@"; }
check() {
  local label="$1"; shift
  if "$@"; then echo "ok   $label"; else echo "FAIL $label"; failures=$((failures + 1)); fi
}

hyprland_lua="$HOME/.config/hypr/hyprland.lua"
cat > "$hyprland_lua" <<'EOF'
require("default.hypr.omarchy")
require("hypr.monitors")
require("hypr.input")
EOF

# --- safe-write-state.sh / bootstrap-state.sh ------------------------------
printf '{"version":1,"profiles":{}}' | bash "$repo/bin/safe-write-state.sh"
state_file="$HOME/.local/state/omarchy/settings/monitor-layout.json"
check "state file written" test -f "$state_file"
check "state file is private" [ "$(stat -c %a "$state_file")" = "600" ]

echo '[{"name":"eDP-1","width":2880,"height":1800,"scale":2,"disabled":false}]' > "$HYPRCTL_MONITORS"
payload=$(bash "$repo/bin/bootstrap-state.sh")
check "bootstrap reports state text" [ "$(jq -r '.state' <<<"$payload")" = '{"version":1,"profiles":{}}' ]
check "bootstrap reports monitors" [ "$(jq -r '.monitors[0].name' <<<"$payload")" = "eDP-1" ]
check "bootstrap reports require missing" [ "$(jq -r '.requireInstalled' <<<"$payload")" = "false" ]
check "bootstrap reports lua missing" [ "$(jq -r '.luaExists' <<<"$payload")" = "false" ]

# Oversized state is refused.
head -c 70000 /dev/zero | tr '\0' 'a' | bash "$repo/bin/safe-write-state.sh" 2>/dev/null
check "oversized state rejected" [ "$(cat "$state_file")" = '{"version":1,"profiles":{}}' ]

# --- install-require.sh -------------------------------------------------------
bash "$repo/bin/install-require.sh" >/dev/null
check "require line inserted after monitors" grep -qx 'require("hypr.monitor-layout")' "$hyprland_lua"
check "require follows hypr.monitors" [ "$(grep -n 'hypr.monitor' "$hyprland_lua" | head -2 | cut -d: -f1 | tr '\n' ' ')" = "2 3 " ]
check "backup created" ls "$HOME/.config/hypr"/hyprland.lua.bak.* >/dev/null 2>&1
bash "$repo/bin/install-require.sh" >/dev/null
check "install is idempotent" [ "$(grep -c 'hypr.monitor-layout' "$hyprland_lua")" = "1" ]

# --- apply-layout.sh ----------------------------------------------------------
: > "$HYPRCTL_LOG"
result=$(printf -- '-- Generated by esemczak.monitor-layout. test\nhl.monitor({ output = "eDP-1" })\n' | bash "$repo/bin/apply-layout.sh")
lua_file="$HOME/.config/hypr/monitor-layout.lua"
check "lua file written" grep -q 'hl.monitor' "$lua_file"
check "apply ok" [ "$(jq -r '.ok' <<<"$result")" = "true" ]
check "apply reloaded" [ "$(jq -r '.reloaded' <<<"$result")" = "true" ]
check "apply sees require" [ "$(jq -r '.requireInstalled' <<<"$result")" = "true" ]
check "hyprctl reload called" grep -q '^reload' "$HYPRCTL_LOG"

printf 'error: something broke\n' > "$HYPRCTL_ERRORS"
result=$(printf -- '-- Generated by esemczak.monitor-layout. bad\n' | bash "$repo/bin/apply-layout.sh")
check "config errors reported" [ "$(jq -r '.ok' <<<"$result")" = "false" ]
check "error text propagated" [ "$(jq -r '.errors[0]' <<<"$result")" = "error: something broke" ]
rm -f "$HYPRCTL_ERRORS"

touch "$GUARD_PAUSED"
: > "$HYPRCTL_LOG"
result=$(printf -- '-- Generated by esemczak.monitor-layout. paused\n' | bash "$repo/bin/apply-layout.sh")
check "paused guard skips reload" not_grep -q '^reload' "$HYPRCTL_LOG"
check "paused guard still ok" [ "$(jq -r '.ok' <<<"$result")" = "true" ]
check "paused guard reports not reloaded" [ "$(jq -r '.reloaded' <<<"$result")" = "false" ]
rm -f "$GUARD_PAUSED"

# Empty input is refused and leaves the file untouched.
before=$(cat "$lua_file")
result=$(printf '' | bash "$repo/bin/apply-layout.sh")
check "empty input refused" [ "$(jq -r '.ok' <<<"$result")" = "false" ]
check "empty input leaves file" [ "$(cat "$lua_file")" = "$before" ]

# Input that does not carry the plugin header is refused.
result=$(printf 'os.execute("rm -rf /")\n' | bash "$repo/bin/apply-layout.sh")
check "unexpected input refused" [ "$(jq -r '.ok' <<<"$result")" = "false" ]

if (( failures )); then echo "$failures failure(s)"; exit 1; fi
echo "all passed"
