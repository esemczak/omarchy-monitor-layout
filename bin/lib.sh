#!/bin/bash
# Shared paths and helpers for the monitor-layout plugin scripts.

set -euo pipefail

readonly ML_MAX_STATE_BYTES=65536
readonly ML_MAX_LUA_BYTES=65536
readonly ML_HEADER='-- Generated by esemczak.monitor-layout'
readonly ML_REQUIRE_LINE='require("hypr.monitor-layout")'
readonly ML_MONITORS_REQUIRE='require("hypr.monitors")'

ml_home="${HOME:?HOME is required}"
ml_config_home="${XDG_CONFIG_HOME:-$ml_home/.config}"
ml_state_home="${XDG_STATE_HOME:-$ml_home/.local/state}"
ml_state_file="$ml_state_home/omarchy/settings/monitor-layout.json"
ml_hypr_dir="$ml_config_home/hypr"
ml_lua_file="$ml_hypr_dir/monitor-layout.lua"
ml_hyprland_lua="$ml_hypr_dir/hyprland.lua"

# Read stdin up to a byte ceiling. Prints the content; fails when the input is
# empty or exceeds the ceiling (one extra byte is read to detect overflow).
ml_read_stdin_bounded() {
  local limit="$1" data
  data=$(head -c "$((limit + 1))"; printf x)
  data=${data%x}
  [[ -n $data ]] || return 1
  (( ${#data} <= limit )) || return 1
  printf '%s' "$data"
}

# Atomically replace a file with stdin, creating the parent with the given mode.
ml_atomic_write() {
  local target="$1" file_mode="$2" dir_mode="${3:-755}"
  local dir tmp
  dir=$(dirname -- "$target")
  mkdir -p -m "$dir_mode" "$dir"
  tmp=$(mktemp -- "$dir/.monitor-layout.XXXXXX")
  cat > "$tmp"
  chmod "$file_mode" "$tmp"
  mv -f -- "$tmp" "$target"
}

ml_require_installed() {
  [[ -f $ml_hyprland_lua ]] && grep -qxF -- "$ML_REQUIRE_LINE" "$ml_hyprland_lua"
}
